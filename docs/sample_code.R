# ※ここでは図と同じ内容の小さなデータフレームを別名で作って試す
#   df（mpg）は上書きされない

# -----------------------------------------------
# left_join：複数のデータフレームを結合する
# -----------------------------------------------

# ※観察単位（都道府県名・年次など）が一致していることを確認してから結合する
df_x <- tibble(
  pref = c("東京都", "東京都", "大阪府", "大阪府"),
  year = c(2019, 2020, 2019, 2020),
  it_investment = c(150, 155, 98, 101)
)
df_y <- tibble(
  pref = c("東京都", "東京都", "大阪府", "大阪府"),
  year = c(2019, 2020, 2019, 2020),
  productivity = c(820, 810, 710, 700)
)

df_joined <- left_join(
  df_x, df_y,             # 結合したいデータフレーム名
  by = c("pref", "year")  # 結合に使用するキー変数
)
df_joined


# -----------------------------------------------
# pivot_longer：横持ち→縦持ちの変換
# -----------------------------------------------

# 横持ちデータ（年次が列名に埋め込まれている）
df_wide <- tibble(
  pref = c("東京都", "大阪府", "愛知県"),
  `2019年` = c(820, 710, 680),
  `2020年` = c(810, 700, 670),
  `2021年` = c(830, 720, 690)
)

df_long <- df_wide |>
  pivot_longer(
    cols = c("2019年", "2020年", "2021年"),  # 縦に変換したい列
    names_to = "year",             # 列名を格納する新しい変数名
    values_to = "productivity"     # 値を格納する新しい変数名
  )
df_long


# -----------------------------------------------
# pivot_wider：縦持ち→横持ちの変換
# -----------------------------------------------

# pivot_longer() の逆変換。発表用の表など、横持ちの方が見やすい場面で使う
# ※分析自体は整然データ（縦持ち）のまま行い、発表用の表だけ横持ちに戻す
df_long |>
  pivot_wider(
    names_from = year,            # 列名にする変数
    values_from = productivity    # 値にする変数
  )


