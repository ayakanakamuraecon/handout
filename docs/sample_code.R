# -----------------------------------------------
# パイプ演算子
# -----------------------------------------------

# |> は、左の結果を右の関数に渡す記号
# ※右側の関数は filter(...) や colSums() のように必ず括弧 () を付ける
# ※古い書き方の %>% も同じ意味で、置き換えて動かせる（|> は R 4.1 以降）
df |> filter(year == 2008)
# df というデータを filter() に渡して、2008年の行だけを取り出す


# -----------------------------------------------
# filter：条件に合う行を取り出す
# -----------------------------------------------

# ※「等しい」はイコール2つ（==）。1つ（=）は代入の意味になるためエラーになる
# ※文字列は必ず "" で囲む
df |> filter(year == 2008)                  # 2008年のデータのみ
df |> filter(cyl >= 6)                      # 気筒数6以上
df |> filter(manufacturer == "toyota")      # トヨタのみ


# -----------------------------------------------
# select：列（変数）を選ぶ
# -----------------------------------------------

df |> select(manufacturer, model, year, hwy)


# -----------------------------------------------
# mutate：新しい変数を作る
# -----------------------------------------------

df |> mutate(hwy_km = hwy * 1.609)          # マイル→kmに変換した新しい列を追加


# -----------------------------------------------
# summarise：集計する
# -----------------------------------------------

# ※n() はデータの件数を数える関数
df |> summarise(
  mean_hwy = mean(hwy),
  max_hwy = max(hwy),
  n = n()
)


# -----------------------------------------------
# group_by：グループ別に集計する
# -----------------------------------------------

# ※arrange() は並び替えの関数。デフォルトは昇順で、desc() で囲むと降順になる
df |>
  group_by(manufacturer) |>
  summarise(mean_hwy = mean(hwy)) |>
  arrange(desc(mean_hwy))    # 降順に並び替え


# -----------------------------------------------
# 欠損値の確認
# -----------------------------------------------

is.na(df) |> colSums()    # 各変数の欠損値の数を確認
df |> filter(is.na(hwy))  # 欠損のある行を表示

# mpg（df）には欠損がないため、欠損を含む練習用データ airquality を
# df とは別のオブジェクト aq に読み込んで確認する
aq <- airquality         # 欠損のある練習用データ（df とは別）
colSums(is.na(aq))       # 各変数の欠損値の数を確認
# → Ozone（オゾン濃度）に37件、Solar.R（日射量）に7件の欠損がある

# 欠損のある行を除外するか、na.rm = TRUE で欠損を除いて計算するかを選ぶ
# ※drop_na() は欠損のある行を取り除く（153行 → 111行）
# ※na.rm = TRUE は行を取り除かず、その関数の計算だけ欠損を無視する
aq |> drop_na()                     # 欠損のある行を除外
mean(aq$Ozone, na.rm = TRUE)         # 欠損を除いて平均を計算


