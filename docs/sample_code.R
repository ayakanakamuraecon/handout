# ===============================================
# 09 回帰分析
# ===============================================

# -----------------------------------------------
# 単回帰分析
# -----------------------------------------------

# Y ~ X の形で書き、data = に使うデータを指定する
model1 <- lm(hwy ~ displ, data = df)   # モデルの推定
summary(model1)                        # 結果の確認

# 結果の読み方：
#   Estimate（係数）：Xが1増えるとYがどれだけ変化するか
#   Pr(>|t|)（p値）：一般的には0.05未満なら統計的に有意
#   R-squared：モデルの当てはまりの良さ（0〜1）


# -----------------------------------------------
# 予測値を計算する
# -----------------------------------------------

# 回帰式 hwy_hat = 35.70 − 3.53 × displ に displ = 2.0 を代入すると、
# 手計算では 35.70 − 3.53 × 2.0 = 28.64
# predict() を使うと、この計算をデータの全行についてまとめて行える
df <- df |> mutate(hwy_hat = predict(model1))
df |> select(displ, hwy, hwy_hat) |> head()

# 手元のデータにない新しい値で予測したいときは newdata を指定する
predict(model1, newdata = data.frame(displ = 3))


# -----------------------------------------------
# 重回帰分析
# -----------------------------------------------

# 説明変数を増やすときは + でつなぐ
model2 <- lm(hwy ~ displ + cyl, data = df)
model3 <- lm(hwy ~ displ + cyl + factor(year), data = df)

summary(model2)
summary(model3)
# ※factor() で変数をカテゴリ型に変換すると、lm() が自動的にダミー変数に
#   変換して回帰式に組み込む。年など、数値ではなくカテゴリとして扱いたい
#   変数に使う


# -----------------------------------------------
# 結果表の作成
# -----------------------------------------------

# modelsummary と flextable は記述統計で読み込み済み。
# セッションを開き直した場合のみ、下の library() を再実行する
library(modelsummary)
library(flextable)

# ※msummary() という書き方も見かけるが、modelsummary() と同じ関数
modelsummary(
  list("モデル1" = model1,
       "モデル2" = model2,
       "モデル3" = model3),
  stars = TRUE,          # 有意水準の星印を表示
  coef_omit = "factor",  # factor() で作ったダミー変数を出力しない
  gof_omit = "IC|Log|F"  # 不要な適合度指標を省略
)


# -----------------------------------------------
# 結果表をWord・PowerPointで保存する
# -----------------------------------------------

modelsummary(model1, output = "flextable") |>
  save_as_docx(path = "regression_table.docx")

modelsummary(model1, output = "flextable") |>
  save_as_pptx(path = "regression_table.pptx")
